// banner spells text in block letters behind the │ $ │ gutter.
func banner(text string) []string {
	rows := []string{"│ ", "$ ", "│ "}
	for _, r := range text {
		for i, g := range font[unicode.ToUpper(r)] {
			rows[i] += g
		}
	}
	return rows
}
